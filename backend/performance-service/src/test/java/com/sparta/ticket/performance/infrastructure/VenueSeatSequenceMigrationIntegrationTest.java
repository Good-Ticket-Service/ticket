package com.sparta.ticket.performance.infrastructure;

import static org.assertj.core.api.Assertions.assertThat;

import com.sparta.ticket.performance.support.PerformanceIntegrationTest;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;

/** 기존 IDENTITY 발급 이력·삭제 좌석·FK 참조를 보존하며 반복 이행해도 번호를 뒤로 돌리지 않는다. */
class VenueSeatSequenceMigrationIntegrationTest extends PerformanceIntegrationTest {
    @Autowired
    private JdbcTemplate jdbc;

    @Test
    void preservesIdsReferencesAndSequenceHighWaterAcrossRepeatedMigration() throws Exception {
        jdbc.execute("CREATE SCHEMA venue_seat_migration_test");
        try {
            jdbc.execute("CREATE TABLE venue_seat_migration_test.p_venue_seats"
                    + " (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, deleted_at timestamp)");
            jdbc.execute("CREATE TABLE venue_seat_migration_test.seat_reference"
                    + " (seat_id bigint REFERENCES venue_seat_migration_test.p_venue_seats(id))");
            jdbc.execute("INSERT INTO venue_seat_migration_test.p_venue_seats VALUES (10,NULL),(9000,now())");
            jdbc.execute("INSERT INTO venue_seat_migration_test.seat_reference VALUES (10),(9000)");
            jdbc.execute("SELECT setval('venue_seat_migration_test.p_venue_seats_id_seq',10000)");
            var before = jdbc.queryForList("SELECT * FROM venue_seat_migration_test.p_venue_seats ORDER BY id");
            String migration = Files.readString(
                            Path.of("../sql/performance-service/migrations/272-venue-seat-sequence.sql"))
                    .replace("performance_schema", "venue_seat_migration_test");
            jdbc.execute(migration);
            assertThat(jdbc.queryForList("SELECT * FROM venue_seat_migration_test.p_venue_seats ORDER BY id"))
                    .isEqualTo(before);
            assertThat(jdbc.queryForList(
                            "SELECT seat_id FROM venue_seat_migration_test.seat_reference ORDER BY seat_id",
                            Long.class))
                    .containsExactly(10L, 9000L);
            long upper =
                    jdbc.queryForObject("SELECT nextval('venue_seat_migration_test.p_venue_seats_seq')", Long.class);
            assertThat(upper - 49).isGreaterThan(10000);
            jdbc.execute(migration);
            long next =
                    jdbc.queryForObject("SELECT nextval('venue_seat_migration_test.p_venue_seats_seq')", Long.class);
            assertThat(next - 49).isGreaterThan(upper);
            assertThat(jdbc.queryForObject(
                            "SELECT increment_by FROM pg_sequences WHERE schemaname='venue_seat_migration_test'"
                                    + " AND sequencename='p_venue_seats_seq'",
                            Long.class))
                    .isEqualTo(50);
            assertThat(jdbc.queryForObject(
                            "INSERT INTO venue_seat_migration_test.p_venue_seats DEFAULT VALUES RETURNING id",
                            Long.class))
                    .isGreaterThan(next);
        } finally {
            jdbc.execute("DROP TABLE venue_seat_migration_test.seat_reference");
            jdbc.execute("DROP TABLE venue_seat_migration_test.p_venue_seats");
            jdbc.execute("DROP SCHEMA venue_seat_migration_test");
        }
    }
}
