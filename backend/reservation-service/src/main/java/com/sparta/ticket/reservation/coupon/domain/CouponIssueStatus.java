package com.sparta.ticket.reservation.coupon.domain;

/**
 * 쿠폰(종류)의 발급 상태. 발급 기간과 현재 시각으로 계산하고 컬럼으로 저장하지 않는다(Coupon.issueStatus).
 * 이 쿠폰을 지금 받을 수 있는 기간인지를 뜻하므로 누가 보든 같다. 회원이 받은 쿠폰 한 장의 상태는 UserCouponStatus다.
 * Note: 저장하지 않아 시각이 지나도 바꿔 줄 작업(스케줄러)이 필요 없고, 발급 UPDATE의 기간 조건과 항상 같은 기준이 된다.
 */
public enum CouponIssueStatus {
    /** 발급 시작 전(현재 < 시작). 받을 수 없고, 할인액·시작 시각·유효 일수를 포함한 모든 항목을 바꿀 수 있다. */
    UPCOMING,
    /** 발급 중(시작 <= 현재 < 종료). 수량이 남았으면 받을 수 있다. 수량이 0이어도 기간 안이면 발급 중이다. */
    ISSUING,
    /**
     * 발급 종료(종료 <= 현재). 종료 정각부터다. 발급 중단은 종료 시각을 현재로 당겨 이 상태가 된다.
     * 다시 열 수 없다(종료 시각 변경 금지). 이미 받은 쿠폰은 자기 만료 시각까지 계속 쓸 수 있다.
     */
    ENDED
}
