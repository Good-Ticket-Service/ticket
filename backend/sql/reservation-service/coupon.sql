-- reservation-service 스키마(reservation_schema)에서 coupon이 소유한 테이블의 현재 DDL. 쿠폰 Entity를 추가·변경하면 이 파일도 같이 고친다.
-- 다른 모듈과 함께 쓰는 schema.sql을 고치지 않도록 테이블 소유대로 파일을 나눴다(#57과 같은 방식).
-- schema.sql, booking.sql, seat.sql 다음에 적용한다. 통합 테스트는 ReservationIntegrationTest가 이 순서로 실행한 뒤 Entity와 대조한다(ddl-auto=validate). dev DB에도 같은 순서로 적용한다.
-- 테이블 이름에 스키마를 붙이지 않는다. 서비스 계정(reservation_app)으로 적용하면 계정 기본 search_path인 reservation_schema에 만들어진다.

-- 쿠폰 정의. coupon 모듈이 소유한다. 명세: docs/tables.md p_coupons
CREATE TABLE p_coupons
(
    coupon_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    -- 쿠폰 구분(#357). 일반(GENERAL) 또는 웰컴(WELCOME). 목록을 나눠 보여 주는 데 쓴다
    category            VARCHAR(20)  NOT NULL DEFAULT 'GENERAL',
    -- 할인 정책(#348). 정액(FIXED)은 discount_amount, 정률(RATE)은 discount_rate·max_discount_amount를 쓴다
    discount_type       VARCHAR(10)  NOT NULL DEFAULT 'FIXED',
    discount_amount     INT,
    discount_rate       INT,
    max_discount_amount INT,
    min_base_amount     INT,
    total_quantity  INT          NOT NULL,
    issued_quantity INT          NOT NULL DEFAULT 0,
    issue_start_at  TIMESTAMP    NOT NULL,
    issue_end_at    TIMESTAMP    NOT NULL,
    valid_days      INT          NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    created_by      VARCHAR(100) NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    updated_by      VARCHAR(100) NOT NULL,
    deleted_at      TIMESTAMP,
    deleted_by      VARCHAR(100),

    -- 종류별로 쓰는 값만 있다. 정률 할인율은 1~99%다(결제 최소 금액 100원 때문에 100%는 무료가 되지 않는다)
    CONSTRAINT ck_p_coupons_discount CHECK (
        (discount_type = 'FIXED' AND discount_amount > 0 AND discount_rate IS NULL AND max_discount_amount IS NULL)
        OR (discount_type = 'RATE' AND discount_amount IS NULL AND discount_rate BETWEEN 1 AND 99
            AND (max_discount_amount IS NULL OR max_discount_amount > 0))),
    CONSTRAINT ck_p_coupons_min_base CHECK (min_base_amount IS NULL OR min_base_amount > 0),
    -- 선착순 발급의 조건부 UPDATE가 놓친 초과 발급을 DB가 마지막으로 막는다
    CONSTRAINT ck_p_coupons_quantity CHECK (total_quantity > 0 AND issued_quantity BETWEEN 0 AND total_quantity),
    -- 시작 전에 발급을 중단하면 두 시각이 같아질 수 있다
    CONSTRAINT ck_p_coupons_period CHECK (issue_start_at <= issue_end_at),
    CONSTRAINT ck_p_coupons_valid_days CHECK (valid_days > 0),
    CONSTRAINT ck_p_coupons_category CHECK (category IN ('GENERAL', 'WELCOME')),
    -- 웰컴 쿠폰은 받은 날부터 7일간 쓸 수 있다(Coupon.WELCOME_VALID_DAYS)
    CONSTRAINT ck_p_coupons_welcome_valid_days CHECK (category <> 'WELCOME' OR valid_days = 7)
);

-- 회원 쿠폰. 회원이 받은 쿠폰 한 장이다. coupon 모듈이 소유한다. 명세: docs/tables.md p_user_coupons
-- user_id는 회원 서비스 ID라 FK가 없다. reservation_id는 booking의 예약이지만 모듈 경계를 지키려고 FK를 두지 않는다
CREATE TABLE p_user_coupons
(
    user_coupon_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    coupon_id       BIGINT       NOT NULL REFERENCES p_coupons (coupon_id),
    -- 발급 시점 할인 정책 복사본(#348). 받은 뒤 쿠폰 정의가 바뀌어도 이미 받은 쿠폰의 조건은 그대로다
    discount_type       VARCHAR(10)  NOT NULL DEFAULT 'FIXED',
    discount_amount     INT,
    discount_rate       INT,
    max_discount_amount INT,
    min_base_amount     INT,
    status          VARCHAR(20)  NOT NULL,
    issued_at       TIMESTAMP    NOT NULL,
    expires_at      TIMESTAMP    NOT NULL,
    reservation_id  BIGINT,
    used_at         TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL,
    created_by      VARCHAR(100) NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    updated_by      VARCHAR(100) NOT NULL,
    deleted_at      TIMESTAMP,
    deleted_by      VARCHAR(100),

    -- 1인 1장. 같은 회원의 동시 발급 요청을 DB가 마지막으로 막는다
    CONSTRAINT uk_p_user_coupons_user_coupon UNIQUE (user_id, coupon_id),
    -- 종류별로 쓰는 값만 있다. 정률 할인율은 1~99%다(결제 최소 금액 100원 때문에 100%는 무료가 되지 않는다)
    CONSTRAINT ck_p_user_coupons_discount CHECK (
        (discount_type = 'FIXED' AND discount_amount > 0 AND discount_rate IS NULL AND max_discount_amount IS NULL)
        OR (discount_type = 'RATE' AND discount_amount IS NULL AND discount_rate BETWEEN 1 AND 99
            AND (max_discount_amount IS NULL OR max_discount_amount > 0))),
    CONSTRAINT ck_p_user_coupons_min_base CHECK (min_base_amount IS NULL OR min_base_amount > 0),
    CONSTRAINT ck_p_user_coupons_status CHECK (status IN ('AVAILABLE', 'RESERVED', 'USED', 'EXPIRED')),
    -- 예매에 잡히거나 쓰인 쿠폰만 예매 ID가 있다
    CONSTRAINT ck_p_user_coupons_reservation CHECK ((status IN ('RESERVED', 'USED')) = (reservation_id IS NOT NULL)),
    CONSTRAINT ck_p_user_coupons_used CHECK ((status = 'USED') = (used_at IS NOT NULL))
);

-- 한 예매에는 쿠폰을 한 장만 잡는다
CREATE UNIQUE INDEX uk_p_user_coupons_reservation ON p_user_coupons (reservation_id) WHERE reservation_id IS NOT NULL;
-- 만료 배치가 기간이 지난 AVAILABLE 쿠폰을 찾는다
CREATE INDEX ix_p_user_coupons_expire ON p_user_coupons (expires_at) WHERE status = 'AVAILABLE';
-- 쿠폰별 받은 회원 조회·개수(Redis 다시 채우기, 남은 수량 대체 계산, 맞추는 작업). UNIQUE (user_id, coupon_id)는 user_id가 앞이라 쓰지 못한다(#323)
CREATE INDEX ix_p_user_coupons_coupon_user ON p_user_coupons (coupon_id, user_id);
