-- performance-service 스키마(performance_schema)의 현재 DDL. Entity를 추가·변경하면 이 파일도 같이 고친다.
-- 통합 테스트(PostgresIntegrationTest)가 이 파일로 테이블을 만든 뒤 Entity와 맞는지 검사한다(ddl-auto=validate).
-- 테이블 이름에 스키마를 붙이지 않는다. 서비스 계정(performance_app)으로 적용하면 계정 기본 search_path인 performance_schema에 만들어진다.
-- Note: 조회용 일반 인덱스는 아직 만들지 않는다. 공개 조회의 성능 기준선을 인덱스 없이 측정한 뒤 단계별로 추가한다.
-- 부분 UNIQUE INDEX는 중복 방지 제약이라 처음부터 둔다. 모두 미삭제 행(deleted_at IS NULL)만 대상으로 한다.

-- 공연장
CREATE TABLE p_venues
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    address    VARCHAR(255) NOT NULL,
    region     VARCHAR(20)  NOT NULL,
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    deleted_at TIMESTAMP,
    deleted_by VARCHAR(100)
);

-- 공연장별 좌석 등급. 가격은 공연별 등급 가격(p_performance_grade_prices)에 둔다
CREATE TABLE p_venue_seat_grades
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id   BIGINT       NOT NULL REFERENCES p_venues (id),
    name       VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    deleted_at TIMESTAMP,
    deleted_by VARCHAR(100),

    CONSTRAINT ck_p_venue_seat_grades_name CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX uq_p_venue_seat_grades_venue_name
    ON p_venue_seat_grades (venue_id, name)
    WHERE deleted_at IS NULL;

-- 공연장 물리 좌석. 등급은 공연장에 고정되며 공연·회차에서 덮어쓰지 않는다
CREATE TABLE p_venue_seats
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id            BIGINT       NOT NULL REFERENCES p_venues (id),
    venue_seat_grade_id BIGINT       NOT NULL REFERENCES p_venue_seat_grades (id),
    section             VARCHAR(20)  NOT NULL,
    row_label           VARCHAR(10)  NOT NULL,
    seat_number         INT          NOT NULL,
    created_at          TIMESTAMP    NOT NULL,
    created_by          VARCHAR(100) NOT NULL,
    updated_at          TIMESTAMP    NOT NULL,
    updated_by          VARCHAR(100) NOT NULL,
    deleted_at          TIMESTAMP,
    deleted_by          VARCHAR(100),

    CONSTRAINT ck_p_venue_seats_section CHECK (btrim(section) <> ''),
    CONSTRAINT ck_p_venue_seats_row_label CHECK (btrim(row_label) <> ''),
    CONSTRAINT ck_p_venue_seats_seat_number CHECK (seat_number > 0)
);

CREATE UNIQUE INDEX uq_p_venue_seats_position
    ON p_venue_seats (venue_id, section, row_label, seat_number)
    WHERE deleted_at IS NULL;

-- 공연. 공개 상태(publication_status)와 운영 상태(operation_status)는 서로 독립이다
CREATE TABLE p_performances
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id          BIGINT       NOT NULL,
    venue_id           BIGINT       NOT NULL REFERENCES p_venues (id),
    title              VARCHAR(200) NOT NULL,
    genre              VARCHAR(20)  NOT NULL,
    age_rating         VARCHAR(20)  NOT NULL,
    running_time       INT          NOT NULL,
    cast_info          VARCHAR(500),
    description        TEXT,
    poster_url         VARCHAR(500),
    publication_status VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    operation_status   VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    published_at       TIMESTAMP(3),
    version            BIGINT       NOT NULL DEFAULT 0,
    created_at         TIMESTAMP    NOT NULL,
    created_by         VARCHAR(100) NOT NULL,
    updated_at         TIMESTAMP    NOT NULL,
    updated_by         VARCHAR(100) NOT NULL,
    deleted_at         TIMESTAMP,
    deleted_by         VARCHAR(100),

    CONSTRAINT ck_p_performances_genre CHECK (genre IN ('CONCERT', 'MUSICAL', 'PLAY', 'SPORTS')),
    CONSTRAINT ck_p_performances_age_rating CHECK (age_rating IN ('ALL', '12', '15', '19')),
    CONSTRAINT ck_p_performances_running_time CHECK (running_time > 0),
    CONSTRAINT ck_p_performances_publication_status CHECK (publication_status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_p_performances_operation_status CHECK (operation_status IN ('ACTIVE', 'CANCELED')),
    -- 공개된 공연에는 최초 공개 시각이 있어야 한다
    CONSTRAINT ck_p_performances_published_at CHECK (publication_status = 'DRAFT' OR published_at IS NOT NULL)
);

-- 공연별 등급 가격. 같은 공연의 모든 회차가 같은 가격을 쓴다
CREATE TABLE p_performance_grade_prices
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id      BIGINT       NOT NULL REFERENCES p_performances (id),
    venue_seat_grade_id BIGINT       NOT NULL REFERENCES p_venue_seat_grades (id),
    price               INT          NOT NULL,
    created_at          TIMESTAMP    NOT NULL,
    created_by          VARCHAR(100) NOT NULL,
    updated_at          TIMESTAMP    NOT NULL,
    updated_by          VARCHAR(100) NOT NULL,
    deleted_at          TIMESTAMP,
    deleted_by          VARCHAR(100),

    CONSTRAINT ck_p_performance_grade_prices_price CHECK (price > 0)
);

CREATE UNIQUE INDEX uq_p_performance_grade_prices_grade
    ON p_performance_grade_prices (performance_id, venue_seat_grade_id)
    WHERE deleted_at IS NULL;

-- 공연 회차. 좌석별 선점·판매 상태는 예매 서비스의 회차 좌석이 관리한다
CREATE TABLE p_schedules
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id             BIGINT       NOT NULL REFERENCES p_performances (id),
    start_at                   TIMESTAMP(3) NOT NULL,
    booking_open_at            TIMESTAMP(3) NOT NULL,
    booking_close_at           TIMESTAMP(3) NOT NULL,
    operation_status           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    seat_setup_status          VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    seat_config_version        BIGINT       NOT NULL DEFAULT 1,
    seat_setup_request_id      VARCHAR(36)  NOT NULL,
    seat_setup_error           VARCHAR(500),
    sales_suspended            BOOLEAN      NOT NULL DEFAULT FALSE,
    suspension_reason          VARCHAR(500),
    canceled_at                TIMESTAMP(3),
    cancel_reason              VARCHAR(500),
    seat_setup_attempts        INT          NOT NULL DEFAULT 0,
    seat_setup_next_attempt_at TIMESTAMP(3),
    version                    BIGINT       NOT NULL DEFAULT 0,
    created_at                 TIMESTAMP    NOT NULL,
    created_by                 VARCHAR(100) NOT NULL,
    updated_at                 TIMESTAMP    NOT NULL,
    updated_by                 VARCHAR(100) NOT NULL,
    deleted_at                 TIMESTAMP,
    deleted_by                 VARCHAR(100),

    -- 공연 시작 후 판매는 지원하지 않는다
    CONSTRAINT ck_p_schedules_booking_period CHECK (booking_open_at < booking_close_at AND booking_close_at <= start_at),
    CONSTRAINT ck_p_schedules_operation_status CHECK (operation_status IN ('ACTIVE', 'CANCELED')),
    CONSTRAINT ck_p_schedules_seat_setup_status CHECK (seat_setup_status IN ('PENDING', 'READY', 'FAILED')),
    CONSTRAINT ck_p_schedules_seat_config_version CHECK (seat_config_version > 0),
    CONSTRAINT ck_p_schedules_seat_setup_attempts CHECK (seat_setup_attempts >= 0)
);

-- 삭제한 회차와 같은 시각으로 다시 등록할 수 있게 미삭제 행만 검사한다
CREATE UNIQUE INDEX uq_p_schedules_start
    ON p_schedules (performance_id, start_at)
    WHERE deleted_at IS NULL;

-- 공연 공통 판매 제외 좌석. 행이 있으면 모든 회차에서 판매하지 않는다
CREATE TABLE p_performance_seat_policies
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id   BIGINT       NOT NULL REFERENCES p_performances (id),
    venue_seat_id    BIGINT       NOT NULL REFERENCES p_venue_seats (id),
    exclusion_reason VARCHAR(255) NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    created_by       VARCHAR(100) NOT NULL,
    updated_at       TIMESTAMP    NOT NULL,
    updated_by       VARCHAR(100) NOT NULL,
    deleted_at       TIMESTAMP,
    deleted_by       VARCHAR(100),

    CONSTRAINT ck_p_performance_seat_policies_reason CHECK (btrim(exclusion_reason) <> '')
);

CREATE UNIQUE INDEX uq_p_performance_seat_policies_seat
    ON p_performance_seat_policies (performance_id, venue_seat_id)
    WHERE deleted_at IS NULL;
