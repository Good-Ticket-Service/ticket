-- fake-pg 스키마(fake_pg_schema)의 DDL. fake PG가 기동할 때마다 실행하므로(spring.sql.init) 모든 문장은 IF NOT EXISTS로 쓴다.
-- 서비스 계정(fake_pg_app)으로 적용하면 계정 기본 search_path인 fake_pg_schema에 만들어진다.
-- 설계: docs/api.md, docs/tables.md의 fake-pg

-- PG 쪽 거래 기록. 토스는 결제 인증 시뮬레이션, 카카오는 결제 준비에서 READY로 만들고, 승인하면 DONE, 취소하면 CANCELED가 된다.
-- payment-service 기록과 대조(대사)하는 상대편 기록이다.
CREATE TABLE IF NOT EXISTS pg_transaction
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider               VARCHAR(20)  NOT NULL,
    payment_key            VARCHAR(200) NOT NULL,
    order_id               VARCHAR(64)  NOT NULL,
    order_name             VARCHAR(100) NOT NULL,
    amount                 INT          NOT NULL,
    status                 VARCHAR(20)  NOT NULL,
    auth_expires_at        TIMESTAMP    NOT NULL,
    requested_at           TIMESTAMP    NOT NULL,
    approved_at            TIMESTAMP,
    canceled_at            TIMESTAMP,
    cancel_reason          VARCHAR(200),
    cancel_transaction_key VARCHAR(200),
    -- 취소된 금액. 전액 취소면 amount, 관리 API의 외부 부분 취소면 그보다 작다
    canceled_amount        INT,
    failure_code           VARCHAR(80),
    -- 카카오 전용. 토스 거래는 NULL
    partner_user_id        VARCHAR(100),
    pg_token               VARCHAR(100),
    updated_at             TIMESTAMP    NOT NULL,

    CONSTRAINT uk_pg_transaction_payment_key UNIQUE (payment_key),
    -- 실제 PG처럼 주문번호 하나에 거래 하나
    CONSTRAINT uk_pg_transaction_order UNIQUE (provider, order_id),
    CONSTRAINT ck_pg_transaction_status CHECK (status IN ('READY', 'DONE', 'CANCELED', 'PARTIAL_CANCELED', 'ABORTED', 'EXPIRED')),
    CONSTRAINT ck_pg_transaction_amount CHECK (amount > 0)
);

-- 카카오 호환 API(#30) 전에 만든 테이블에 컬럼을 더한다. CREATE TABLE IF NOT EXISTS는 이미 있는 테이블을 바꾸지 않는다.
ALTER TABLE pg_transaction ADD COLUMN IF NOT EXISTS partner_user_id VARCHAR(100);
ALTER TABLE pg_transaction ADD COLUMN IF NOT EXISTS pg_token VARCHAR(100);

-- 외부 취소 재현(Task 12) 전에 만든 테이블에 부분 취소 상태와 취소 금액을 더한다. 기존 취소 기록의 canceled_amount는 NULL이며 승인액으로 본다.
ALTER TABLE pg_transaction ADD COLUMN IF NOT EXISTS canceled_amount INT;
ALTER TABLE pg_transaction DROP CONSTRAINT IF EXISTS ck_pg_transaction_status;
ALTER TABLE pg_transaction ADD CONSTRAINT ck_pg_transaction_status
    CHECK (status IN ('READY', 'DONE', 'CANCELED', 'PARTIAL_CANCELED', 'ABORTED', 'EXPIRED'));

-- 멱등 키 응답 저장. 같은 키로 다시 오면 저장한 응답(성공·업무 거절)을 그대로 돌려준다. 5xx·429는 저장하지 않는다.
CREATE TABLE IF NOT EXISTS pg_idempotency_record
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider        VARCHAR(20)  NOT NULL,
    idempotency_key VARCHAR(300) NOT NULL,
    operation       VARCHAR(20)  NOT NULL,
    fingerprint     VARCHAR(64)  NOT NULL,
    state           VARCHAR(20)  NOT NULL,
    status_code     INT,
    response_body   TEXT,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,

    CONSTRAINT uk_pg_idempotency_key UNIQUE (provider, idempotency_key),
    CONSTRAINT ck_pg_idempotency_state CHECK (state IN ('PROCESSING', 'COMPLETED'))
);

-- PG 지급대행(판매자 정산 지급) 흉내. 결제 거래·결제 멱등 레코드와 섞지 않는다.
-- 접수 때 결과(완료·실패)와 처리 시각을 정해 두고, 처리 시각이 지난 뒤 조회하면 그 결과로 확정한다. 한 번 정한 결과는 다시 추첨하지 않는다.
CREATE TABLE IF NOT EXISTS pg_payout
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(200) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL,
    payout_id       VARCHAR(100) NOT NULL,
    seller_ref      VARCHAR(100) NOT NULL,
    account_ref     VARCHAR(100) NOT NULL,
    holder_masked   VARCHAR(100) NOT NULL,
    amount          BIGINT       NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    outcome         VARCHAR(20)  NOT NULL,
    failure_code    VARCHAR(40),
    requested_at    TIMESTAMP    NOT NULL,
    process_at      TIMESTAMP    NOT NULL,
    decided_at      TIMESTAMP,

    CONSTRAINT uk_pg_payout_key UNIQUE (idempotency_key),
    CONSTRAINT uk_pg_payout_id UNIQUE (payout_id),
    CONSTRAINT ck_pg_payout_amount CHECK (amount > 0),
    CONSTRAINT ck_pg_payout_status CHECK (status IN ('ACCEPTED', 'PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_pg_payout_outcome CHECK (outcome IN ('COMPLETED', 'FAILED')),
    CONSTRAINT ck_pg_payout_failure CHECK ((outcome = 'FAILED') = (failure_code IS NOT NULL))
);
