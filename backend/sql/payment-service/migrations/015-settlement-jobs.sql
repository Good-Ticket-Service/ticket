-- 정산 반영 작업(#304). 다시 실행해도 안전하다.
CREATE TABLE IF NOT EXISTS p_settlement_jobs
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id      BIGINT       NOT NULL,
    reason          VARCHAR(20)  NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    attempts        INT          NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP    NOT NULL,
    last_error      VARCHAR(80),
    done_at         TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL,
    created_by      VARCHAR(100) NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    updated_by      VARCHAR(100) NOT NULL,
    deleted_at      TIMESTAMP,
    deleted_by      VARCHAR(100),

    CONSTRAINT fk_p_settlement_jobs_payment FOREIGN KEY (payment_id) REFERENCES p_payments (id),
    CONSTRAINT uk_p_settlement_jobs_payment_reason UNIQUE (payment_id, reason),
    CONSTRAINT ck_p_settlement_jobs_reason CHECK (reason IN ('PAYMENT_APPROVED', 'REFUND_COMPLETED')),
    CONSTRAINT ck_p_settlement_jobs_status CHECK (status IN ('PENDING', 'DONE', 'BLOCKED')),
    CONSTRAINT ck_p_settlement_jobs_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_p_settlement_jobs_done CHECK ((status = 'DONE') = (done_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_p_settlement_jobs_due ON p_settlement_jobs (next_attempt_at, id) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS ix_p_settlement_jobs_blocked ON p_settlement_jobs (id) WHERE status = 'BLOCKED';

-- 전환 전 데이터: 승인됐는데 정상 SALE이 없는 결제(포착을 꺼 둔 기간 등)를 한 번만 작업으로 옮긴다.
-- 전환 뒤에는 작업이 결제 확정과 함께 저장되므로 보충 잡이 결제 전체를 다시 훑지 않는다.
-- Note: 결제 전체를 한 번 읽는다. 운영 DB에서는 거래가 적은 시간에 실행한다.
INSERT INTO p_settlement_jobs (payment_id, reason, status, next_attempt_at, created_at, created_by, updated_at, updated_by)
SELECT p.id, 'PAYMENT_APPROVED', 'PENDING', localtimestamp, localtimestamp, 'migration-015', localtimestamp, 'migration-015'
FROM p_payments p
WHERE p.status IN ('DONE', 'CANCELED') AND p.approved_at IS NOT NULL AND p.deleted_at IS NULL
  AND NOT EXISTS (SELECT 1 FROM p_settlement_items i WHERE i.payment_id = p.id AND i.kind = 'SALE'
                  AND i.status <> 'UNPOSTED' AND i.deleted_at IS NULL)
ON CONFLICT (payment_id, reason) DO NOTHING;
