-- #363: Kafka 격리 이력과 운영 재처리 Outbox. 금융 성공 receipt는 기존 작업/집계에 남긴다.
BEGIN;
CREATE TABLE p_financial_consumer_incidents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  stage VARCHAR(20) NOT NULL CHECK(stage IN ('POSTING','PROJECTION')),
  group_id VARCHAR(200) NOT NULL,source_topic VARCHAR(249) NOT NULL,
  source_partition INT NOT NULL CHECK(source_partition>=0),source_offset BIGINT NOT NULL CHECK(source_offset>=0),
  payload_hash VARCHAR(64) NOT NULL CHECK(payload_hash ~ '^[0-9a-f]{64}$'),
  reason VARCHAR(80) NOT NULL CHECK(reason ~ '^[A-Z_]+$'),
  source_job_id BIGINT REFERENCES p_settlement_jobs(id),
  source_build_id UUID REFERENCES p_settlement_projection_builds(id),
  source_fact_key VARCHAR(160),
  status VARCHAR(24) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','REPLAY_REQUESTED','RESOLVED')),
  deliveries INT NOT NULL DEFAULT 1 CHECK(deliveries>0),
  dlt_confirmed_at TIMESTAMP,resolved_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),updated_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),
  UNIQUE(stage,group_id,source_topic,source_partition,source_offset),
  CHECK((status='RESOLVED')=(resolved_at IS NOT NULL)),
  CHECK(source_job_id IS NULL OR stage='POSTING'),
  CHECK(source_build_id IS NULL OR stage='PROJECTION')
);
CREATE INDEX ix_financial_incident_open ON p_financial_consumer_incidents(id) WHERE status<>'RESOLVED';

CREATE TABLE p_financial_replay_commands (
  command_id UUID PRIMARY KEY,
  incident_id UUID NOT NULL REFERENCES p_financial_consumer_incidents(incident_id),
  action VARCHAR(16) NOT NULL CHECK(action IN ('REPLAY','RESOLVE')),
  input_hash VARCHAR(64) NOT NULL CHECK(input_hash ~ '^[0-9a-f]{64}$'),
  actor VARCHAR(200) NOT NULL,reason VARCHAR(500) NOT NULL,
  status VARCHAR(16) NOT NULL CHECK(status IN ('REQUESTED','PUBLISHED','DONE','DENIED')),
  explanation VARCHAR(80) NOT NULL,
  target_topic VARCHAR(249),message_key VARCHAR(30),payload TEXT,
  lease_token UUID,lease_until TIMESTAMP,attempts INT NOT NULL DEFAULT 0 CHECK(attempts>=0),
  next_attempt_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),published_at TIMESTAMP,last_error VARCHAR(80),
  created_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),updated_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),
  CHECK((lease_token IS NULL)=(lease_until IS NULL)),
  CHECK(status NOT IN ('REQUESTED','PUBLISHED') OR (target_topic IS NOT NULL AND message_key IS NOT NULL AND payload IS NOT NULL))
);
CREATE UNIQUE INDEX uk_financial_replay_inflight ON p_financial_replay_commands(incident_id)
  WHERE status IN ('REQUESTED','PUBLISHED');
CREATE INDEX ix_financial_replay_due ON p_financial_replay_commands(next_attempt_at,command_id)
  WHERE status='REQUESTED';
CREATE INDEX ix_settlement_job_financial_pending ON p_settlement_jobs(created_at,id)
  WHERE transport='KAFKA' AND status='PENDING';
COMMIT;
