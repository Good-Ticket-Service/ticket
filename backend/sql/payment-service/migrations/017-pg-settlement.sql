-- PG 정산 명세 대사·입금 회계. payment_app 계정으로 적용한다.
CREATE TABLE IF NOT EXISTS p_pg_settlement_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(20) NOT NULL CHECK (provider IN ('TOSS','KAKAO')),
    settlement_date DATE NOT NULL,
    snapshot_id VARCHAR(200) NOT NULL,
    line_count BIGINT NOT NULL CHECK (line_count >= 0),
    amount BIGINT NOT NULL,
    fee BIGINT NOT NULL,
    carry_in BIGINT NOT NULL CHECK (carry_in >= 0),
    payout BIGINT NOT NULL CHECK (payout >= 0),
    carry_out BIGINT NOT NULL CHECK (carry_out >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVING' CHECK (status IN ('RECEIVING','RECEIVED','MATCHED','POSTED')),
    created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    deleted_at TIMESTAMP,
    deleted_by VARCHAR(100),
    UNIQUE (provider, settlement_date),
    CHECK (amount - fee - carry_in + carry_out = payout),
    CHECK (payout = 0 OR carry_out = 0),
    CHECK (deleted_at IS NULL)
);

CREATE TABLE IF NOT EXISTS p_pg_settlement_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_id BIGINT NOT NULL REFERENCES p_pg_settlement_days(id),
    provider VARCHAR(20) NOT NULL,
    line_key VARCHAR(240) NOT NULL,
    payment_key VARCHAR(200) NOT NULL,
    order_id VARCHAR(64) NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type IN ('APPROVAL','CANCEL')),
    amount BIGINT NOT NULL,
    fee BIGINT NOT NULL,
    occurred_at TIMESTAMP NOT NULL,
    clearing_amount BIGINT NOT NULL DEFAULT 0,
    suspense_amount BIGINT NOT NULL DEFAULT 0,
    matched BOOLEAN NOT NULL DEFAULT FALSE,
    adjusted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    deleted_at TIMESTAMP,
    deleted_by VARCHAR(100),
    UNIQUE (provider,line_key),
    CHECK (line_key = payment_key || ':' || type),
    CHECK ((type='APPROVAL' AND amount>0 AND fee>=0) OR (type='CANCEL' AND amount<0 AND fee<=0)),
    CHECK (deleted_at IS NULL)
);
CREATE INDEX IF NOT EXISTS ix_pg_lines_day ON p_pg_settlement_lines(day_id,id);
CREATE INDEX IF NOT EXISTS ix_pg_lines_payment ON p_pg_settlement_lines(provider,payment_key);
CREATE INDEX IF NOT EXISTS ix_pg_lines_suspense ON p_pg_settlement_lines(provider,payment_key,id)
    WHERE suspense_amount<>0 AND NOT adjusted;

CREATE TABLE IF NOT EXISTS p_pg_reconcile_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(20) NOT NULL,
    line_key VARCHAR(240) NOT NULL,
    line_id BIGINT REFERENCES p_pg_settlement_lines(id),
    settlement_date DATE NOT NULL,
    expected_date DATE,
    expected_amount BIGINT,
    expected_fee BIGINT,
    policy_version VARCHAR(40),
    finding VARCHAR(30) NOT NULL CHECK (finding IN ('MATCHED','PENDING','ONLY_IN_PG','ONLY_IN_OURS',
        'STATUS_MISMATCH','AMOUNT_MISMATCH','FEE_MISMATCH','DATE_MISMATCH')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN','RESOLVED')),
    reason VARCHAR(500),
    resolved_by VARCHAR(100),
    resolved_at TIMESTAMP,
    resolution_history JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    deleted_at TIMESTAMP,
    deleted_by VARCHAR(100),
    UNIQUE (provider,line_key),
    CHECK (deleted_at IS NULL)
);
CREATE INDEX IF NOT EXISTS ix_pg_results_open ON p_pg_reconcile_results(provider,id) WHERE status='OPEN';

