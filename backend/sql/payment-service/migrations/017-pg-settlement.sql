-- Batch 5 PostgreSQL 메타데이터. 애플리케이션 기동 시 자동 생성하지 않는다.
-- 기존 지급 확정도 현금 출금으로 연결한다. 원래 지급 기록은 수정하지 않고 추가 분개만 남긴다.
WITH cash_journals AS (
    INSERT INTO p_ledger_transactions(source_type,source_id,action,seller_id,statement_id,payout_id,
      occurred_at,created_at,created_by,updated_at,updated_by)
    SELECT 'PAYOUT_CASH',t.source_id,'POST',t.seller_id,t.statement_id,t.payout_id,t.occurred_at,
      LOCALTIMESTAMP,'SYSTEM',LOCALTIMESTAMP,'SYSTEM'
    FROM p_ledger_transactions t JOIN p_payouts p ON p.id=t.source_id AND p.status='DONE'
    WHERE t.source_type='PAYOUT' AND t.action='DONE'
    ON CONFLICT(source_type,source_id,action) DO NOTHING RETURNING id,payout_id
)
INSERT INTO p_ledger_entries(transaction_id,line_no,account,debit,credit,created_at,created_by,updated_at,updated_by)
SELECT c.id,1,'PAYOUT_CLEARING',p.amount,0,LOCALTIMESTAMP,'SYSTEM',LOCALTIMESTAMP,'SYSTEM'
  FROM cash_journals c JOIN p_payouts p ON p.id=c.payout_id
UNION ALL
SELECT c.id,2,'CASH',0,p.amount,LOCALTIMESTAMP,'SYSTEM',LOCALTIMESTAMP,'SYSTEM'
  FROM cash_journals c JOIN p_payouts p ON p.id=c.payout_id;

CREATE TABLE IF NOT EXISTS BATCH_JOB_INSTANCE (
    JOB_INSTANCE_ID BIGINT PRIMARY KEY, VERSION BIGINT, JOB_NAME VARCHAR(100) NOT NULL,
    JOB_KEY VARCHAR(32) NOT NULL, CONSTRAINT JOB_INST_UN UNIQUE (JOB_NAME, JOB_KEY));
CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION (
    JOB_EXECUTION_ID BIGINT PRIMARY KEY, VERSION BIGINT, JOB_INSTANCE_ID BIGINT NOT NULL REFERENCES BATCH_JOB_INSTANCE,
    CREATE_TIME TIMESTAMP NOT NULL, START_TIME TIMESTAMP DEFAULT NULL, END_TIME TIMESTAMP DEFAULT NULL,
    STATUS VARCHAR(10), EXIT_CODE VARCHAR(2500), EXIT_MESSAGE VARCHAR(2500), LAST_UPDATED TIMESTAMP);
CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_PARAMS (
    JOB_EXECUTION_ID BIGINT NOT NULL REFERENCES BATCH_JOB_EXECUTION,
    PARAMETER_NAME VARCHAR(100) NOT NULL, PARAMETER_TYPE VARCHAR(100) NOT NULL,
    PARAMETER_VALUE VARCHAR(2500), IDENTIFYING CHAR(1) NOT NULL);
CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION (
    STEP_EXECUTION_ID BIGINT PRIMARY KEY, VERSION BIGINT NOT NULL, STEP_NAME VARCHAR(100) NOT NULL,
    JOB_EXECUTION_ID BIGINT NOT NULL REFERENCES BATCH_JOB_EXECUTION, CREATE_TIME TIMESTAMP NOT NULL,
    START_TIME TIMESTAMP, END_TIME TIMESTAMP, STATUS VARCHAR(10), COMMIT_COUNT BIGINT, READ_COUNT BIGINT,
    FILTER_COUNT BIGINT, WRITE_COUNT BIGINT, READ_SKIP_COUNT BIGINT, WRITE_SKIP_COUNT BIGINT,
    PROCESS_SKIP_COUNT BIGINT, ROLLBACK_COUNT BIGINT, EXIT_CODE VARCHAR(2500), EXIT_MESSAGE VARCHAR(2500), LAST_UPDATED TIMESTAMP);
CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION_CONTEXT (
    STEP_EXECUTION_ID BIGINT PRIMARY KEY REFERENCES BATCH_STEP_EXECUTION,
    SHORT_CONTEXT VARCHAR(2500) NOT NULL, SERIALIZED_CONTEXT TEXT);
CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_CONTEXT (
    JOB_EXECUTION_ID BIGINT PRIMARY KEY REFERENCES BATCH_JOB_EXECUTION,
    SHORT_CONTEXT VARCHAR(2500) NOT NULL, SERIALIZED_CONTEXT TEXT);
