-- 정산 복식 원장 테이블 추가(Task 20-2). 기존 결제·환불·정산 항목 데이터는 바꾸지 않는다. 다시 실행해도 안전하다.
BEGIN;
-- 정산 복식 원장 헤더(settlement-design 3·4.5절). 업무 1건(판매·환불·상계·지급)마다 한 행이고 수정·삭제하지 않는다.
-- 정정은 원거래를 가리키는 반대 분개로 한다. statement_id·payout_id는 해당 테이블을 도입하는 작업에서 외래 키를 건다.
CREATE TABLE IF NOT EXISTS p_ledger_transactions
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type             VARCHAR(20)  NOT NULL,
    source_id               BIGINT       NOT NULL,
    action                  VARCHAR(20)  NOT NULL,
    seller_id               BIGINT       NOT NULL,
    payment_id              BIGINT,
    refund_id               BIGINT,
    statement_id            BIGINT,
    payout_id               BIGINT,
    policy_version          VARCHAR(40),
    reverses_transaction_id BIGINT,
    occurred_at             TIMESTAMP    NOT NULL,
    created_at              TIMESTAMP    NOT NULL,
    created_by              VARCHAR(100) NOT NULL,
    updated_at              TIMESTAMP    NOT NULL,
    updated_by              VARCHAR(100) NOT NULL,
    deleted_at              TIMESTAMP,
    deleted_by              VARCHAR(100),

    CONSTRAINT uk_p_ledger_transactions_key UNIQUE (source_type, source_id, action),
    CONSTRAINT fk_p_ledger_transactions_payment FOREIGN KEY (payment_id) REFERENCES p_payments (id),
    CONSTRAINT fk_p_ledger_transactions_refund FOREIGN KEY (refund_id) REFERENCES p_refunds (id),
    CONSTRAINT fk_p_ledger_transactions_reverses FOREIGN KEY (reverses_transaction_id) REFERENCES p_ledger_transactions (id),
    CONSTRAINT ck_p_ledger_transactions_key CHECK (
        (source_type = 'SALE' AND action = 'POST')
        OR (source_type = 'REFUND' AND action IN ('REVERSE', 'RECEIVABLE'))
        OR (source_type = 'STATEMENT' AND action = 'OFFSET')
        OR (source_type = 'PAYOUT' AND action = 'DONE')),
    -- 판매·환불 분개는 결제와 고정 정책을 가리킨다. 환불 분개는 원천 환불을 가리킨다
    CONSTRAINT ck_p_ledger_transactions_sale_refund CHECK (source_type NOT IN ('SALE', 'REFUND') OR (
        payment_id IS NOT NULL AND policy_version IS NOT NULL)),
    CONSTRAINT ck_p_ledger_transactions_refund CHECK (source_type <> 'REFUND' OR refund_id = source_id),
    CONSTRAINT ck_p_ledger_transactions_reverses CHECK ((action = 'REVERSE') = (reverses_transaction_id IS NOT NULL)),
    -- 추가 전용 원장이라 논리 삭제하지 않는다
    CONSTRAINT ck_p_ledger_transactions_not_deleted CHECK (deleted_at IS NULL)
);

-- 환불 1건은 발행 전 REVERSE 또는 발행 뒤 RECEIVABLE 중 하나만. 원거래 1건의 반대 분개도 하나만
CREATE UNIQUE INDEX IF NOT EXISTS uk_p_ledger_transactions_refund ON p_ledger_transactions (source_id) WHERE source_type = 'REFUND';
CREATE UNIQUE INDEX IF NOT EXISTS uk_p_ledger_transactions_reverses ON p_ledger_transactions (reverses_transaction_id)
    WHERE reverses_transaction_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_p_ledger_transactions_seller ON p_ledger_transactions (seller_id);

-- 정산 복식 원장 줄. 한 줄에 차변·대변 중 한쪽만 양수다.
-- Note: 행 CHECK·UNIQUE는 여러 줄의 차변 합 = 대변 합을 보장하지 않는다. 균형은 저장 전 도메인 검증과 내부 대조가 맡는다.
CREATE TABLE IF NOT EXISTS p_ledger_entries
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT       NOT NULL,
    line_no        INT          NOT NULL,
    account        VARCHAR(30)  NOT NULL,
    debit          BIGINT       NOT NULL,
    credit         BIGINT       NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    created_by     VARCHAR(100) NOT NULL,
    updated_at     TIMESTAMP    NOT NULL,
    updated_by     VARCHAR(100) NOT NULL,
    deleted_at     TIMESTAMP,
    deleted_by     VARCHAR(100),

    CONSTRAINT uk_p_ledger_entries_line UNIQUE (transaction_id, line_no),
    CONSTRAINT fk_p_ledger_entries_transaction FOREIGN KEY (transaction_id) REFERENCES p_ledger_transactions (id),
    CONSTRAINT ck_p_ledger_entries_line_no CHECK (line_no >= 1),
    CONSTRAINT ck_p_ledger_entries_account CHECK (account IN ('PG_CLEARING', 'DISCOUNT_EXPENSE', 'SELLER_RECEIVABLE',
        'SELLER_PAYABLE', 'COMMISSION_REVENUE', 'BOOKING_FEE_REVENUE', 'VAT_PAYABLE', 'PAYOUT_CLEARING')),
    CONSTRAINT ck_p_ledger_entries_one_side CHECK ((debit > 0 AND credit = 0) OR (debit = 0 AND credit > 0)),
    CONSTRAINT ck_p_ledger_entries_not_deleted CHECK (deleted_at IS NULL)
);
COMMIT;
