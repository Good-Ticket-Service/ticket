-- 정산서·명세·지급(READY)·판매자 기준 행 테이블과 미뤄 둔 외래 키 추가(Task 20-5). 기존 데이터는 바꾸지 않는다. 다시 실행해도 안전하다.
BEGIN;
-- 판매자 정산 기준 행(settlement-design 3절 8번). 판매자마다 하나이고 정산서 발행이 판매자 단위로 잠그는 행이다.
-- 계좌 정보는 판매자가 등록하기 전까지 비어 있다. 이 행이 있다고 수취 계좌가 등록된 것은 아니다.
CREATE TABLE IF NOT EXISTS p_seller_payout_accounts
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id     BIGINT       NOT NULL,
    account_ref   VARCHAR(100),
    holder_masked VARCHAR(100),
    version       BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP    NOT NULL,
    created_by    VARCHAR(100) NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,
    updated_by    VARCHAR(100) NOT NULL,
    deleted_at    TIMESTAMP,
    deleted_by    VARCHAR(100),

    CONSTRAINT uk_p_seller_payout_accounts_seller UNIQUE (seller_id),
    CONSTRAINT ck_p_seller_payout_accounts_version CHECK (version >= 0)
);

-- 판매자·회차별 정산서(settlement-design 3절 4번·5절). 발행 때 합계를 고정하고 바꾸지 않는다.
-- 늦게 정상화된 SALE은 같은 회차의 다음 sequence 정산서로 나간다.
CREATE TABLE IF NOT EXISTS p_settlement_statements
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id      BIGINT       NOT NULL,
    schedule_id    BIGINT       NOT NULL,
    sequence       INT          NOT NULL,
    cutoff         TIMESTAMP    NOT NULL,
    sale_total     BIGINT       NOT NULL,
    offset_total   BIGINT       NOT NULL,
    payable_amount BIGINT       NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    issued_at      TIMESTAMP    NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMP    NOT NULL,
    created_by     VARCHAR(100) NOT NULL,
    updated_at     TIMESTAMP    NOT NULL,
    updated_by     VARCHAR(100) NOT NULL,
    deleted_at     TIMESTAMP,
    deleted_by     VARCHAR(100),

    CONSTRAINT uk_p_settlement_statements_sequence UNIQUE (seller_id, schedule_id, sequence),
    CONSTRAINT ck_p_settlement_statements_sequence CHECK (sequence >= 0),
    -- 판매가 있어야 발행하고, 지급액 = 판매 합계 − 상계액 ≥ 0
    CONSTRAINT ck_p_settlement_statements_amounts CHECK (
        sale_total > 0 AND offset_total >= 0 AND payable_amount >= 0
        AND payable_amount = sale_total - offset_total),
    CONSTRAINT ck_p_settlement_statements_status CHECK (
        (status = 'ISSUED' AND payable_amount > 0) OR (status = 'NO_PAYOUT' AND payable_amount = 0)),
    CONSTRAINT ck_p_settlement_statements_version CHECK (version >= 0),
    CONSTRAINT ck_p_settlement_statements_not_deleted CHECK (deleted_at IS NULL)
);

-- 정산서 명세행. SALE은 한 번만 편입하고, DEDUCTION은 여러 정산서에 나눠 상계할 수 있다.
CREATE TABLE IF NOT EXISTS p_settlement_statement_lines
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT       NOT NULL,
    item_id      BIGINT       NOT NULL,
    kind         VARCHAR(20)  NOT NULL,
    amount       BIGINT       NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    created_by   VARCHAR(100) NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    updated_by   VARCHAR(100) NOT NULL,
    deleted_at   TIMESTAMP,
    deleted_by   VARCHAR(100),

    CONSTRAINT uk_p_settlement_statement_lines_item UNIQUE (statement_id, item_id),
    CONSTRAINT fk_p_settlement_statement_lines_statement FOREIGN KEY (statement_id) REFERENCES p_settlement_statements (id),
    CONSTRAINT fk_p_settlement_statement_lines_item FOREIGN KEY (item_id) REFERENCES p_settlement_items (id),
    CONSTRAINT ck_p_settlement_statement_lines_kind CHECK (kind IN ('SALE', 'DEDUCTION')),
    CONSTRAINT ck_p_settlement_statement_lines_amount CHECK (amount > 0),
    CONSTRAINT ck_p_settlement_statement_lines_not_deleted CHECK (deleted_at IS NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_p_settlement_statement_lines_sale ON p_settlement_statement_lines (item_id)
    WHERE kind = 'SALE';

-- 판매자 지급(settlement-design 3절 6번·7.2절). 이 단계는 정산서 발행이 만드는 READY까지만 둔다.
-- 실행권·멱등 키·계좌 스냅샷·결과 확정 컬럼은 지급 실행 작업에서 추가한다.
CREATE TABLE IF NOT EXISTS p_payouts
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id    BIGINT       NOT NULL,
    seller_id       BIGINT       NOT NULL,
    amount          BIGINT       NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    attempt         INT          NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL,
    created_by      VARCHAR(100) NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    updated_by      VARCHAR(100) NOT NULL,
    deleted_at      TIMESTAMP,
    deleted_by      VARCHAR(100),

    CONSTRAINT uk_p_payouts_statement UNIQUE (statement_id),
    CONSTRAINT fk_p_payouts_statement FOREIGN KEY (statement_id) REFERENCES p_settlement_statements (id),
    CONSTRAINT ck_p_payouts_amount CHECK (amount > 0),
    CONSTRAINT ck_p_payouts_status CHECK (status IN ('READY')),
    CONSTRAINT ck_p_payouts_attempt CHECK (attempt >= 0),
    CONSTRAINT ck_p_payouts_version CHECK (version >= 0),
    CONSTRAINT ck_p_payouts_not_deleted CHECK (deleted_at IS NULL)
);

-- 발행 후보 조회: 정산 가능일이 지난 PENDING SALE, 판매자의 미회수 차감
CREATE INDEX IF NOT EXISTS ix_p_settlement_items_pending_sale ON p_settlement_items (eligible_at, schedule_id, seller_id)
    WHERE kind = 'SALE' AND status = 'PENDING';
CREATE INDEX IF NOT EXISTS ix_p_settlement_items_open_deduction ON p_settlement_items (seller_id)
    WHERE kind = 'DEDUCTION' AND status = 'OPEN';

-- 앞선 작업에서 대상 테이블이 없어 미뤄 둔 외래 키(정산 항목·원장 → 정산서·지급). 이미 있으면 건너뛴다
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_p_settlement_items_statement') THEN
        ALTER TABLE p_settlement_items ADD CONSTRAINT fk_p_settlement_items_statement FOREIGN KEY (statement_id) REFERENCES p_settlement_statements (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_p_ledger_transactions_statement') THEN
        ALTER TABLE p_ledger_transactions ADD CONSTRAINT fk_p_ledger_transactions_statement FOREIGN KEY (statement_id) REFERENCES p_settlement_statements (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_p_ledger_transactions_payout') THEN
        ALTER TABLE p_ledger_transactions ADD CONSTRAINT fk_p_ledger_transactions_payout FOREIGN KEY (payout_id) REFERENCES p_payouts (id);
    END IF;
END
$$;
COMMIT;
