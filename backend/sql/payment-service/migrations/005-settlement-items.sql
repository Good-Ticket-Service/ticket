-- 판매자 정산 항목 테이블 추가(Task 20-1). 기존 결제·환불 데이터는 바꾸지 않는다. 다시 실행해도 안전하다.
BEGIN;
-- 판매자 정산 항목(settlement-design 3절). SALE은 승인 결제 1건, DEDUCTION은 정산서 발행 뒤 환불 1건.
-- 금액·정책·달력 버전은 만들 때 고정한다. 계산 실패 SALE(UNPOSTED)도 결제 입력과 사유를 남긴다.
-- statement_id는 정산서 테이블을 도입하는 작업에서 외래 키를 건다.
CREATE TABLE IF NOT EXISTS p_settlement_items
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind              VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    seller_id         BIGINT       NOT NULL,
    payment_id        BIGINT       NOT NULL,
    refund_id         BIGINT,
    origin_item_id    BIGINT,
    performance_id    BIGINT,
    schedule_id       BIGINT,
    schedule_start_at TIMESTAMP,
    approved_at       TIMESTAMP,
    gross_amount      INT,
    discount_amount   INT,
    booking_fee       INT,
    paid_amount       INT,
    commission        INT,
    commission_vat    INT,
    seller_amount     INT,
    booking_fee_net   INT,
    booking_fee_vat   INT,
    policy_version    VARCHAR(40),
    calendar_version  VARCHAR(40),
    eligible_at       TIMESTAMP,
    hold_reason       VARCHAR(40),
    failure_reason    VARCHAR(80),
    statement_id      BIGINT,
    principal         BIGINT,
    remaining         BIGINT,
    version           BIGINT       NOT NULL DEFAULT 0,
    created_at        TIMESTAMP    NOT NULL,
    created_by        VARCHAR(100) NOT NULL,
    updated_at        TIMESTAMP    NOT NULL,
    updated_by        VARCHAR(100) NOT NULL,
    deleted_at        TIMESTAMP,
    deleted_by        VARCHAR(100),

    CONSTRAINT fk_p_settlement_items_payment FOREIGN KEY (payment_id) REFERENCES p_payments (id),
    CONSTRAINT fk_p_settlement_items_refund FOREIGN KEY (refund_id) REFERENCES p_refunds (id),
    CONSTRAINT fk_p_settlement_items_origin FOREIGN KEY (origin_item_id) REFERENCES p_settlement_items (id),
    CONSTRAINT ck_p_settlement_items_kind_status CHECK (
        (kind = 'SALE' AND status IN ('UNPOSTED', 'PENDING', 'HELD', 'ON_STATEMENT', 'CANCELED'))
        OR (kind = 'DEDUCTION' AND status IN ('OPEN', 'CLEARED'))),
    CONSTRAINT ck_p_settlement_items_hold_reason CHECK (
        hold_reason IS NULL OR hold_reason IN ('REFUND_IN_PROGRESS', 'MISSING_SCHEDULE_START', 'CALENDAR_NOT_COVERED')),
    -- SALE은 결제 스냅샷(입력 금액)을 항상 가진다. DEDUCTION 전용 값은 없다
    CONSTRAINT ck_p_settlement_items_sale_source CHECK (kind <> 'SALE' OR (
        performance_id IS NOT NULL AND schedule_id IS NOT NULL AND approved_at IS NOT NULL
        AND gross_amount IS NOT NULL AND discount_amount IS NOT NULL AND booking_fee IS NOT NULL AND paid_amount IS NOT NULL
        AND origin_item_id IS NULL AND principal IS NULL AND remaining IS NULL)),
    -- 계산 실패는 사유만, 계산 결과는 없다. 0원 정상 거래로 위장하지 않는다
    CONSTRAINT ck_p_settlement_items_unposted CHECK (kind <> 'SALE' OR status <> 'UNPOSTED' OR (
        failure_reason IS NOT NULL AND commission IS NULL AND seller_amount IS NULL AND policy_version IS NULL)),
    -- 분개한 SALE은 금액·버전이 모두 있고 보존식 E + P = N + F + V + Bn + Bv와 E = G − P + Bf를 지킨다
    CONSTRAINT ck_p_settlement_items_posted CHECK (kind <> 'SALE' OR status = 'UNPOSTED' OR (
        failure_reason IS NULL
        AND commission IS NOT NULL AND commission_vat IS NOT NULL AND seller_amount IS NOT NULL
        AND booking_fee_net IS NOT NULL AND booking_fee_vat IS NOT NULL
        AND policy_version IS NOT NULL AND calendar_version IS NOT NULL
        AND gross_amount > 0 AND discount_amount >= 0 AND booking_fee >= 0
        AND commission >= 0 AND commission_vat >= 0 AND seller_amount >= 0 AND booking_fee_net >= 0 AND booking_fee_vat >= 0
        AND paid_amount::BIGINT = gross_amount::BIGINT - discount_amount + booking_fee
        AND paid_amount::BIGINT + discount_amount
            = seller_amount::BIGINT + commission + commission_vat + booking_fee_net + booking_fee_vat)),
    CONSTRAINT ck_p_settlement_items_pending CHECK (status <> 'PENDING' OR (eligible_at IS NOT NULL AND hold_reason IS NULL)),
    CONSTRAINT ck_p_settlement_items_held CHECK (status <> 'HELD' OR hold_reason IS NOT NULL),
    CONSTRAINT ck_p_settlement_items_on_statement CHECK (status <> 'ON_STATEMENT' OR statement_id IS NOT NULL),
    CONSTRAINT ck_p_settlement_items_deduction CHECK (kind <> 'DEDUCTION' OR (
        refund_id IS NOT NULL AND origin_item_id IS NOT NULL
        AND principal > 0 AND remaining >= 0 AND remaining <= principal
        AND ((status = 'OPEN' AND remaining > 0) OR (status = 'CLEARED' AND remaining = 0)))),
    CONSTRAINT ck_p_settlement_items_version CHECK (version >= 0)
);

-- 결제마다 SALE 하나, 환불마다 DEDUCTION 하나. SALE도 환불 ID를 기록하므로 refund_id 전체 UNIQUE를 두지 않는다
CREATE UNIQUE INDEX IF NOT EXISTS uk_p_settlement_items_sale_payment ON p_settlement_items (payment_id) WHERE kind = 'SALE';
CREATE UNIQUE INDEX IF NOT EXISTS uk_p_settlement_items_deduction_refund ON p_settlement_items (refund_id) WHERE kind = 'DEDUCTION';
COMMIT;
