-- 정산 전체 대조 실행 기록(Task 20-11). 다시 실행해도 안전하다.
CREATE TABLE IF NOT EXISTS p_settlement_reconcile_runs
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status               VARCHAR(20)  NOT NULL,
    started_at           TIMESTAMP    NOT NULL,
    finished_at          TIMESTAMP,
    violations           BIGINT,
    provider_checked     INT,
    provider_unreachable INT,
    error                VARCHAR(200),

    CONSTRAINT ck_p_settlement_reconcile_runs_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_p_settlement_reconcile_runs_finished CHECK ((status = 'RUNNING') = (finished_at IS NULL)),
    CONSTRAINT ck_p_settlement_reconcile_runs_succeeded CHECK (status <> 'SUCCEEDED' OR (
        violations IS NOT NULL AND provider_checked IS NOT NULL AND provider_unreachable IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_p_settlement_reconcile_runs_latest ON p_settlement_reconcile_runs (status, finished_at DESC);

-- 대조 항목별 위반 수와 확인용 ID 일부. 금액·계좌 원문은 남기지 않는다
CREATE TABLE IF NOT EXISTS p_settlement_reconcile_results
(
    run_id     BIGINT       NOT NULL,
    check_name VARCHAR(40)  NOT NULL,
    violations BIGINT       NOT NULL,
    sample     VARCHAR(400),

    CONSTRAINT pk_p_settlement_reconcile_results PRIMARY KEY (run_id, check_name),
    CONSTRAINT fk_p_settlement_reconcile_results_run FOREIGN KEY (run_id) REFERENCES p_settlement_reconcile_runs (id),
    CONSTRAINT ck_p_settlement_reconcile_results_violations CHECK (violations >= 0)
);
