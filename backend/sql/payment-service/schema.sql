    command_id VARCHAR(80) PRIMARY KEY,
    input_hash VARCHAR(64) NOT NULL,
    payment_id BIGINT NOT NULL,
    refund_id BIGINT NOT NULL,
    action VARCHAR(10) NOT NULL CHECK (action IN ('RETRY','RESUME')),
    actor VARCHAR(200) NOT NULL,
    reason VARCHAR(40) NOT NULL,
    result VARCHAR(40) NOT NULL CHECK (result IN ('APPLIED','CONFIRMED_CANCELED','DENIED','STALE','PG_UNKNOWN')),
    explanation VARCHAR(80) NOT NULL,
    expected_state VARCHAR(160) NOT NULL,
    before_state VARCHAR(160) NOT NULL,
    after_state VARCHAR(160) NOT NULL,
    inquiry VARCHAR(40) NOT NULL,
    processed_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    deleted_at TIMESTAMP,
    deleted_by VARCHAR(100)
);
CREATE INDEX ix_refund_operations_history ON p_refund_operation_commands (refund_id, processed_at DESC, command_id DESC);

-- 판매자 정산 항목(settlement-design 3절). SALE은 승인 결제 1건, DEDUCTION은 정산서 발행 뒤 환불 1건.
-- 금액·정책·달력 버전은 만들 때 고정한다. 계산 실패 SALE(UNPOSTED)도 결제 입력과 사유를 남긴다.
-- statement_id는 정산서 테이블을 도입하는 작업에서 외래 키를 건다.
CREATE TABLE p_settlement_items
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind              VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    seller_id         BIGINT       NOT NULL,
    payment_id        BIGINT       NOT NULL,
    refund_id         BIGINT,
    origin_item_id    BIGINT,
    performance_id    BIGINT,
    schedule_id       BIGINT,
    schedule_start_at TIMESTAMP,
    approved_at       TIMESTAMP,
    gross_amount      INT,
    discount_amount   INT,
    booking_fee       INT,
    paid_amount       INT,
    commission        INT,
    commission_vat    INT,
    seller_amount     INT,
    booking_fee_net   INT,
    booking_fee_vat   INT,
    policy_version    VARCHAR(40),
    calendar_version  VARCHAR(40),
    eligible_at       TIMESTAMP,
    hold_reason       VARCHAR(40),
    failure_reason    VARCHAR(80),
    statement_id      BIGINT,
    principal         BIGINT,
    remaining         BIGINT,
    version           BIGINT       NOT NULL DEFAULT 0,
    created_at        TIMESTAMP    NOT NULL,
    created_by        VARCHAR(100) NOT NULL,
    updated_at        TIMESTAMP    NOT NULL,
    updated_by        VARCHAR(100) NOT NULL,
    deleted_at        TIMESTAMP,
    deleted_by        VARCHAR(100),

    CONSTRAINT fk_p_settlement_items_payment FOREIGN KEY (payment_id) REFERENCES p_payments (id),
    CONSTRAINT fk_p_settlement_items_refund FOREIGN KEY (refund_id) REFERENCES p_refunds (id),
    CONSTRAINT fk_p_settlement_items_origin FOREIGN KEY (origin_item_id) REFERENCES p_settlement_items (id),
    CONSTRAINT ck_p_settlement_items_kind_status CHECK (
        (kind = 'SALE' AND status IN ('UNPOSTED', 'PENDING', 'HELD', 'ON_STATEMENT', 'CANCELED'))
        OR (kind = 'DEDUCTION' AND status IN ('OPEN', 'CLEARED'))),
    CONSTRAINT ck_p_settlement_items_hold_reason CHECK (
        hold_reason IS NULL OR hold_reason IN ('REFUND_IN_PROGRESS', 'MISSING_SCHEDULE_START', 'CALENDAR_NOT_COVERED')),
    -- SALE은 결제 스냅샷(입력 금액)을 항상 가진다. DEDUCTION 전용 값은 없다
    CONSTRAINT ck_p_settlement_items_sale_source CHECK (kind <> 'SALE' OR (
        performance_id IS NOT NULL AND schedule_id IS NOT NULL AND approved_at IS NOT NULL
        AND gross_amount IS NOT NULL AND discount_amount IS NOT NULL AND booking_fee IS NOT NULL AND paid_amount IS NOT NULL
        AND origin_item_id IS NULL AND principal IS NULL AND remaining IS NULL)),
    -- 계산 실패는 사유만, 계산 결과는 없다. 0원 정상 거래로 위장하지 않는다
    CONSTRAINT ck_p_settlement_items_unposted CHECK (kind <> 'SALE' OR status <> 'UNPOSTED' OR (
        failure_reason IS NOT NULL AND commission IS NULL AND seller_amount IS NULL AND policy_version IS NULL)),
    -- 분개한 SALE은 금액·버전이 모두 있고 보존식 E + P = N + F + V + Bn + Bv와 E = G − P + Bf를 지킨다
    CONSTRAINT ck_p_settlement_items_posted CHECK (kind <> 'SALE' OR status = 'UNPOSTED' OR (
        failure_reason IS NULL
        AND commission IS NOT NULL AND commission_vat IS NOT NULL AND seller_amount IS NOT NULL
        AND booking_fee_net IS NOT NULL AND booking_fee_vat IS NOT NULL
        AND policy_version IS NOT NULL AND calendar_version IS NOT NULL
        AND gross_amount > 0 AND discount_amount >= 0 AND booking_fee >= 0
        AND commission >= 0 AND commission_vat >= 0 AND seller_amount >= 0 AND booking_fee_net >= 0 AND booking_fee_vat >= 0
        AND paid_amount::BIGINT = gross_amount::BIGINT - discount_amount + booking_fee
        AND paid_amount::BIGINT + discount_amount
            = seller_amount::BIGINT + commission + commission_vat + booking_fee_net + booking_fee_vat)),
    CONSTRAINT ck_p_settlement_items_pending CHECK (status <> 'PENDING' OR (eligible_at IS NOT NULL AND hold_reason IS NULL)),
    CONSTRAINT ck_p_settlement_items_held CHECK (status <> 'HELD' OR hold_reason IS NOT NULL),
    CONSTRAINT ck_p_settlement_items_on_statement CHECK (status <> 'ON_STATEMENT' OR statement_id IS NOT NULL),
    CONSTRAINT ck_p_settlement_items_deduction CHECK (kind <> 'DEDUCTION' OR (
        refund_id IS NOT NULL AND origin_item_id IS NOT NULL
        AND principal > 0 AND remaining >= 0 AND remaining <= principal
        AND ((status = 'OPEN' AND remaining > 0) OR (status = 'CLEARED' AND remaining = 0)))),
    CONSTRAINT ck_p_settlement_items_version CHECK (version >= 0)
);

-- 결제마다 SALE 하나, 환불마다 DEDUCTION 하나. SALE도 환불 ID를 기록하므로 refund_id 전체 UNIQUE를 두지 않는다
CREATE UNIQUE INDEX uk_p_settlement_items_sale_payment ON p_settlement_items (payment_id) WHERE kind = 'SALE';
CREATE UNIQUE INDEX uk_p_settlement_items_deduction_refund ON p_settlement_items (refund_id) WHERE kind = 'DEDUCTION';

-- 정산 복식 원장 헤더(settlement-design 3·4.5절). 업무 1건(판매·환불·상계·지급)마다 한 행이고 수정·삭제하지 않는다.
-- 정정은 원거래를 가리키는 반대 분개로 한다. statement_id·payout_id는 해당 테이블을 도입하는 작업에서 외래 키를 건다.
CREATE TABLE p_ledger_transactions
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type             VARCHAR(20)  NOT NULL,
    source_id               BIGINT       NOT NULL,
    action                  VARCHAR(20)  NOT NULL,
    seller_id               BIGINT       NOT NULL,
    payment_id              BIGINT,
    refund_id               BIGINT,
    statement_id            BIGINT,
    payout_id               BIGINT,
    policy_version          VARCHAR(40),
    reverses_transaction_id BIGINT,
    occurred_at             TIMESTAMP    NOT NULL,
    created_at              TIMESTAMP    NOT NULL,
    created_by              VARCHAR(100) NOT NULL,
    updated_at              TIMESTAMP    NOT NULL,
    updated_by              VARCHAR(100) NOT NULL,
    deleted_at              TIMESTAMP,
    deleted_by              VARCHAR(100),

    CONSTRAINT uk_p_ledger_transactions_key UNIQUE (source_type, source_id, action),
    CONSTRAINT fk_p_ledger_transactions_payment FOREIGN KEY (payment_id) REFERENCES p_payments (id),
    CONSTRAINT fk_p_ledger_transactions_refund FOREIGN KEY (refund_id) REFERENCES p_refunds (id),
    CONSTRAINT fk_p_ledger_transactions_reverses FOREIGN KEY (reverses_transaction_id) REFERENCES p_ledger_transactions (id),
    CONSTRAINT ck_p_ledger_transactions_key CHECK (
        (source_type = 'SALE' AND action = 'POST')
        OR (source_type = 'REFUND' AND action IN ('REVERSE', 'RECEIVABLE'))
        OR (source_type = 'STATEMENT' AND action = 'OFFSET')
        OR (source_type = 'PAYOUT' AND action = 'DONE')),
    -- 판매·환불 분개는 결제와 고정 정책을 가리킨다. 환불 분개는 원천 환불을 가리킨다
    CONSTRAINT ck_p_ledger_transactions_sale_refund CHECK (source_type NOT IN ('SALE', 'REFUND') OR (
        payment_id IS NOT NULL AND policy_version IS NOT NULL)),
    CONSTRAINT ck_p_ledger_transactions_refund CHECK (source_type <> 'REFUND' OR refund_id = source_id),
    CONSTRAINT ck_p_ledger_transactions_reverses CHECK ((action = 'REVERSE') = (reverses_transaction_id IS NOT NULL)),
    -- 추가 전용 원장이라 논리 삭제하지 않는다
    CONSTRAINT ck_p_ledger_transactions_not_deleted CHECK (deleted_at IS NULL)
);

-- 환불 1건은 발행 전 REVERSE 또는 발행 뒤 RECEIVABLE 중 하나만. 원거래 1건의 반대 분개도 하나만
CREATE UNIQUE INDEX uk_p_ledger_transactions_refund ON p_ledger_transactions (source_id) WHERE source_type = 'REFUND';
CREATE UNIQUE INDEX uk_p_ledger_transactions_reverses ON p_ledger_transactions (reverses_transaction_id)
    WHERE reverses_transaction_id IS NOT NULL;
CREATE INDEX ix_p_ledger_transactions_seller ON p_ledger_transactions (seller_id);

-- 정산 복식 원장 줄. 한 줄에 차변·대변 중 한쪽만 양수다.
-- Note: 행 CHECK·UNIQUE는 여러 줄의 차변 합 = 대변 합을 보장하지 않는다. 균형은 저장 전 도메인 검증과 내부 대조가 맡는다.
CREATE TABLE p_ledger_entries
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT       NOT NULL,
    line_no        INT          NOT NULL,
    account        VARCHAR(30)  NOT NULL,
    debit          BIGINT       NOT NULL,
    credit         BIGINT       NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    created_by     VARCHAR(100) NOT NULL,
    updated_at     TIMESTAMP    NOT NULL,
    updated_by     VARCHAR(100) NOT NULL,
    deleted_at     TIMESTAMP,
    deleted_by     VARCHAR(100),

    CONSTRAINT uk_p_ledger_entries_line UNIQUE (transaction_id, line_no),
    CONSTRAINT fk_p_ledger_entries_transaction FOREIGN KEY (transaction_id) REFERENCES p_ledger_transactions (id),
    CONSTRAINT ck_p_ledger_entries_line_no CHECK (line_no >= 1),
    CONSTRAINT ck_p_ledger_entries_account CHECK (account IN ('PG_CLEARING', 'DISCOUNT_EXPENSE', 'SELLER_RECEIVABLE',
        'SELLER_PAYABLE', 'COMMISSION_REVENUE', 'BOOKING_FEE_REVENUE', 'VAT_PAYABLE', 'PAYOUT_CLEARING')),
    CONSTRAINT ck_p_ledger_entries_one_side CHECK ((debit > 0 AND credit = 0) OR (debit = 0 AND credit > 0)),
    CONSTRAINT ck_p_ledger_entries_not_deleted CHECK (deleted_at IS NULL)
);

-- 판매자 정산 기준 행(settlement-design 3절 8번). 판매자마다 하나이고 정산서 발행이 판매자 단위로 잠그는 행이다.
-- 계좌 정보는 판매자가 등록하기 전까지 비어 있다. 이 행이 있다고 수취 계좌가 등록된 것은 아니다.
CREATE TABLE p_seller_payout_accounts
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id     BIGINT       NOT NULL,
    bank_code     VARCHAR(10),
    account_ref   VARCHAR(100),
    holder_masked VARCHAR(100),
    account_masked VARCHAR(40),
    version       BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP    NOT NULL,
    created_by    VARCHAR(100) NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,
    updated_by    VARCHAR(100) NOT NULL,
    deleted_at    TIMESTAMP,
    deleted_by    VARCHAR(100),

    CONSTRAINT uk_p_seller_payout_accounts_seller UNIQUE (seller_id),
    -- 계좌는 한 번에 등록한다. 계좌번호 원문은 저장하지 않고 모의 참조·마스킹 값만 둔다
    CONSTRAINT ck_p_seller_payout_accounts_registered CHECK (
        (account_ref IS NULL AND bank_code IS NULL AND account_masked IS NULL AND holder_masked IS NULL)
        OR (account_ref IS NOT NULL AND bank_code IS NOT NULL AND account_masked IS NOT NULL AND holder_masked IS NOT NULL)),
    CONSTRAINT ck_p_seller_payout_accounts_version CHECK (version >= 0)
);

-- 판매자·회차별 정산서(settlement-design 3절 4번·5절). 발행 때 합계를 고정하고 바꾸지 않는다.
-- 늦게 정상화된 SALE은 같은 회차의 다음 sequence 정산서로 나간다.
CREATE TABLE p_settlement_statements
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id      BIGINT       NOT NULL,
    schedule_id    BIGINT       NOT NULL,
    sequence       INT          NOT NULL,
    cutoff         TIMESTAMP    NOT NULL,
    sale_total     BIGINT       NOT NULL,
    offset_total   BIGINT       NOT NULL,
    payable_amount BIGINT       NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    issued_at      TIMESTAMP    NOT NULL,
    paid_at        TIMESTAMP,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMP    NOT NULL,
    created_by     VARCHAR(100) NOT NULL,
    updated_at     TIMESTAMP    NOT NULL,
    updated_by     VARCHAR(100) NOT NULL,
    deleted_at     TIMESTAMP,
    deleted_by     VARCHAR(100),

    CONSTRAINT uk_p_settlement_statements_sequence UNIQUE (seller_id, schedule_id, sequence),
    CONSTRAINT ck_p_settlement_statements_sequence CHECK (sequence >= 0),
    -- 판매가 있어야 발행하고, 지급액 = 판매 합계 − 상계액 ≥ 0
    CONSTRAINT ck_p_settlement_statements_amounts CHECK (
        sale_total > 0 AND offset_total >= 0 AND payable_amount >= 0
        AND payable_amount = sale_total - offset_total),
    CONSTRAINT ck_p_settlement_statements_status CHECK (
        (status = 'ISSUED' AND payable_amount > 0 AND paid_at IS NULL)
        OR (status = 'NO_PAYOUT' AND payable_amount = 0 AND paid_at IS NULL)
        OR (status = 'PAID' AND payable_amount > 0 AND paid_at IS NOT NULL)),
    CONSTRAINT ck_p_settlement_statements_version CHECK (version >= 0),
    CONSTRAINT ck_p_settlement_statements_not_deleted CHECK (deleted_at IS NULL)
);

-- 정산서 명세행. SALE은 한 번만 편입하고, DEDUCTION은 여러 정산서에 나눠 상계할 수 있다.
CREATE TABLE p_settlement_statement_lines
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT       NOT NULL,
    item_id      BIGINT       NOT NULL,
    kind         VARCHAR(20)  NOT NULL,
    amount       BIGINT       NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    created_by   VARCHAR(100) NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    updated_by   VARCHAR(100) NOT NULL,
    deleted_at   TIMESTAMP,
    deleted_by   VARCHAR(100),

    CONSTRAINT uk_p_settlement_statement_lines_item UNIQUE (statement_id, item_id),
    CONSTRAINT fk_p_settlement_statement_lines_statement FOREIGN KEY (statement_id) REFERENCES p_settlement_statements (id),
    CONSTRAINT fk_p_settlement_statement_lines_item FOREIGN KEY (item_id) REFERENCES p_settlement_items (id),
    CONSTRAINT ck_p_settlement_statement_lines_kind CHECK (kind IN ('SALE', 'DEDUCTION')),
    CONSTRAINT ck_p_settlement_statement_lines_amount CHECK (amount > 0),
    CONSTRAINT ck_p_settlement_statement_lines_not_deleted CHECK (deleted_at IS NULL)
);
CREATE UNIQUE INDEX uk_p_settlement_statement_lines_sale ON p_settlement_statement_lines (item_id)
    WHERE kind = 'SALE';

-- 판매자 지급(settlement-design 3절 6번·7.2절). 이 단계는 정산서 발행이 만드는 READY까지만 둔다.
-- 실행권·멱등 키·계좌 스냅샷·결과 확정 컬럼은 지급 실행 작업에서 추가한다.
CREATE TABLE p_payouts
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id    BIGINT       NOT NULL,
    seller_id       BIGINT       NOT NULL,
    amount          BIGINT       NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    attempt         INT          NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP,
    -- 실행권 획득 때 찍는 멱등 키와 계좌 스냅샷. 같은 attempt 동안 모든 요청이 같은 키·금액·계좌다
    idempotency_key     VARCHAR(100),
    bank_code           VARCHAR(10),
    account_ref         VARCHAR(100),
    holder_masked       VARCHAR(100),
    account_version     BIGINT,
    -- 지급대행이 알려 준 마지막 상태(ACCEPTED·PROCESSING)와 결과 불명(UNKNOWN)을 구분한다
    provider_status     VARCHAR(20),
    external_payout_id  VARCHAR(100),
    failure_code        VARCHAR(40),
    -- 응답이 기대와 다르면 다시 요청하지 않고 조회만 한다
    inquiry_only        BOOLEAN      NOT NULL DEFAULT FALSE,
    verification_reason VARCHAR(80),
    requested_at        TIMESTAMP,
    done_at             TIMESTAMP,
    last_error          VARCHAR(80),
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL,
    created_by      VARCHAR(100) NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    updated_by      VARCHAR(100) NOT NULL,
    deleted_at      TIMESTAMP,
    deleted_by      VARCHAR(100),

    CONSTRAINT uk_p_payouts_statement UNIQUE (statement_id),
    CONSTRAINT fk_p_payouts_statement FOREIGN KEY (statement_id) REFERENCES p_settlement_statements (id),
    CONSTRAINT ck_p_payouts_amount CHECK (amount > 0),
    CONSTRAINT ck_p_payouts_status CHECK (status IN ('READY', 'REQUESTED', 'DONE', 'FAILED')),
    CONSTRAINT ck_p_payouts_provider_status CHECK (provider_status IS NULL OR provider_status IN ('ACCEPTED', 'PROCESSING', 'UNKNOWN')),
    -- 실행권을 얻은 뒤의 지급은 키·계좌 스냅샷을 반드시 가진다
    CONSTRAINT ck_p_payouts_claimed CHECK (status = 'READY' OR (
        idempotency_key IS NOT NULL AND bank_code IS NOT NULL AND account_ref IS NOT NULL
        AND holder_masked IS NOT NULL AND account_version IS NOT NULL AND requested_at IS NOT NULL)),
    CONSTRAINT ck_p_payouts_done CHECK (status <> 'DONE' OR (external_payout_id IS NOT NULL AND done_at IS NOT NULL)),
    CONSTRAINT ck_p_payouts_failed CHECK ((status = 'FAILED') = (failure_code IS NOT NULL)),
    CONSTRAINT ck_p_payouts_attempt CHECK (attempt >= 0),
    CONSTRAINT ck_p_payouts_version CHECK (version >= 0),
    CONSTRAINT ck_p_payouts_not_deleted CHECK (deleted_at IS NULL)
);
CREATE UNIQUE INDEX uk_p_payouts_idempotency_key ON p_payouts (idempotency_key) WHERE idempotency_key IS NOT NULL;
-- 지급 실행 후보: 실행할 시각이 된 READY
CREATE INDEX ix_p_payouts_ready ON p_payouts (next_attempt_at) WHERE status = 'READY';

-- 지급 운영 명령(Task 20-10). 상태 변경과 같은 트랜잭션에 최종 결과를 남긴다. 같은 command_id는 결과를 재현한다
CREATE TABLE p_payout_operation_commands
(
    command_id   VARCHAR(80)  PRIMARY KEY,
    input_hash   VARCHAR(64)  NOT NULL,
    payout_id    BIGINT       NOT NULL,
    action       VARCHAR(10)  NOT NULL,
    actor        VARCHAR(200) NOT NULL,
    reason       VARCHAR(40)  NOT NULL,
    note         VARCHAR(200) NOT NULL,
    result       VARCHAR(20)  NOT NULL,
    explanation  VARCHAR(80)  NOT NULL,
    expected_state VARCHAR(160) NOT NULL,
    before_state VARCHAR(160) NOT NULL,
    after_state  VARCHAR(160) NOT NULL,
    processed_at TIMESTAMP    NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    created_by   VARCHAR(100) NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    updated_by   VARCHAR(100) NOT NULL,
    deleted_at   TIMESTAMP,
    deleted_by   VARCHAR(100),

    CONSTRAINT fk_p_payout_operation_commands_payout FOREIGN KEY (payout_id) REFERENCES p_payouts (id),
    CONSTRAINT ck_p_payout_operation_commands_action CHECK (action IN ('RETRY')),
    CONSTRAINT ck_p_payout_operation_commands_result CHECK (result IN ('APPLIED', 'DENIED', 'STALE')),
    CONSTRAINT ck_p_payout_operation_commands_not_deleted CHECK (deleted_at IS NULL)
);
CREATE INDEX ix_p_payout_operation_commands_history
    ON p_payout_operation_commands (payout_id, processed_at DESC, command_id DESC);

-- 정산 전체 대조 실행 기록(Task 20-11). 대조는 읽기만 하고 고치지 않는다. 결과를 남겨 재시작 뒤에도 마지막 성공 시각과 위반 수를
-- 경보가 볼 수 있게 한다. 지급을 막는 보류 상태가 아니다(지급 차단은 정산서 단위 게이트가 한다)
CREATE TABLE p_settlement_reconcile_runs
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status               VARCHAR(20)  NOT NULL,
    started_at           TIMESTAMP    NOT NULL,
    finished_at          TIMESTAMP,
    violations           BIGINT,
    provider_checked     INT,
    provider_unreachable INT,
    error                VARCHAR(200),

    CONSTRAINT ck_p_settlement_reconcile_runs_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_p_settlement_reconcile_runs_finished CHECK ((status = 'RUNNING') = (finished_at IS NULL)),
    CONSTRAINT ck_p_settlement_reconcile_runs_succeeded CHECK (status <> 'SUCCEEDED' OR (
        violations IS NOT NULL AND provider_checked IS NOT NULL AND provider_unreachable IS NOT NULL))
);
CREATE INDEX ix_p_settlement_reconcile_runs_latest ON p_settlement_reconcile_runs (status, finished_at DESC);

-- 대조 항목별 위반 수와 확인용 ID 일부. 금액·계좌 원문은 남기지 않는다
CREATE TABLE p_settlement_reconcile_results
(
    run_id     BIGINT       NOT NULL,
    check_name VARCHAR(40)  NOT NULL,
    violations BIGINT       NOT NULL,
    sample     VARCHAR(400),

    CONSTRAINT pk_p_settlement_reconcile_results PRIMARY KEY (run_id, check_name),
    CONSTRAINT fk_p_settlement_reconcile_results_run FOREIGN KEY (run_id) REFERENCES p_settlement_reconcile_runs (id),
    CONSTRAINT ck_p_settlement_reconcile_results_violations CHECK (violations >= 0)
);

-- 발행 후보 조회: 정산 가능일이 지난 PENDING SALE, 판매자의 미회수 차감
CREATE INDEX ix_p_settlement_items_pending_sale ON p_settlement_items (eligible_at, schedule_id, seller_id)
    WHERE kind = 'SALE' AND status = 'PENDING';
CREATE INDEX ix_p_settlement_items_open_deduction ON p_settlement_items (seller_id)
