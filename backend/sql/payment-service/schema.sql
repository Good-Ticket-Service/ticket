-- payment-service 스키마(payment_schema)의 현재 DDL. Entity를 추가·변경하면 이 파일도 같이 고친다.
-- 통합 테스트(PostgresIntegrationTest)가 이 파일로 테이블을 만든 뒤 Entity와 맞는지 검사한다(ddl-auto=validate).
-- 테이블 이름에 스키마를 붙이지 않는다. 서비스 계정(payment_app)으로 적용하면 계정 기본 search_path인 payment_schema에 만들어진다.
-- 설계: docs/architecture.md, docs/tables.md

CREATE TABLE p_payments
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             VARCHAR(64)  NOT NULL,
    reservation_id       BIGINT       NOT NULL,
    user_id              BIGINT       NOT NULL,
    seller_id            BIGINT       NOT NULL,
    performance_id       BIGINT       NOT NULL,
    schedule_id          BIGINT       NOT NULL,
    pg_provider          VARCHAR(20)  NOT NULL,
    pg_transaction_id    VARCHAR(200),
    checkout_url         VARCHAR(500),
    expires_at           TIMESTAMP    NOT NULL,
    -- 회차 시작 시각(KST). 결제 준비의 선택 필드이며, 없으면 판매자 정산을 보류한다
    schedule_start_at    TIMESTAMP,
    total_price          INT          NOT NULL,
    discount_amount      INT          NOT NULL DEFAULT 0,
    amount               INT          NOT NULL,
    status               VARCHAR(20)  NOT NULL,
    failure_code         VARCHAR(80),
    failure_message      VARCHAR(255),
    confirm_requested_at TIMESTAMP,
    approve_requested_at TIMESTAMP,
    approved_at          TIMESTAMP,
    failed_at            TIMESTAMP,
    reconcile_count      INT          NOT NULL DEFAULT 0,
    next_reconcile_at    TIMESTAMP,
    reconcile_checkpoints_minutes VARCHAR(1024),
    reconcile_retry_count INT NOT NULL DEFAULT 0,
    reconcile_unknown_since TIMESTAMP,
    next_attempt_at      TIMESTAMP,
    recovery_started_at  TIMESTAMP,
    recovery_attempts    INT          NOT NULL DEFAULT 0,
    last_error           VARCHAR(80),
    created_at           TIMESTAMP    NOT NULL,
    created_by           VARCHAR(100) NOT NULL,
    updated_at           TIMESTAMP    NOT NULL,
    updated_by           VARCHAR(100) NOT NULL,
    deleted_at           TIMESTAMP,
    deleted_by           VARCHAR(100),

    CONSTRAINT uk_p_payments_order_id UNIQUE (order_id),
    -- 토스 paymentKey·카카오 tid는 한 결제에만 쓰인다. 재사용·조작된 인증값을 DB가 한 번 더 막는다
    CONSTRAINT uk_p_payments_pg_transaction UNIQUE (pg_provider, pg_transaction_id),
    CONSTRAINT ck_p_payments_reconcile_count CHECK (reconcile_count >= 0 AND
        ((reconcile_checkpoints_minutes IS NULL AND reconcile_count = 0) OR
         (reconcile_checkpoints_minutes IS NOT NULL AND reconcile_count <= cardinality(string_to_array(reconcile_checkpoints_minutes, ','))))),
    CONSTRAINT ck_p_payments_reconcile_state CHECK (next_reconcile_at IS NULL OR
        (status = 'FAILED' AND approve_requested_at IS NOT NULL AND failed_at IS NOT NULL
            AND reconcile_checkpoints_minutes IS NOT NULL
            AND reconcile_count < cardinality(string_to_array(reconcile_checkpoints_minutes, ',')))),
    CONSTRAINT ck_p_payments_reconcile_retry CHECK (reconcile_retry_count >= 0 AND
        ((reconcile_retry_count = 0 AND reconcile_unknown_since IS NULL) OR
         (reconcile_retry_count > 0 AND reconcile_unknown_since IS NOT NULL))),
    CONSTRAINT ck_p_payments_status CHECK (status IN ('READY', 'IN_PROGRESS', 'DONE', 'FAILED', 'CANCELED')),
    CONSTRAINT ck_p_payments_pg_provider CHECK (pg_provider IN ('TOSS', 'KAKAO')),
    CONSTRAINT ck_p_payments_amount CHECK (
        discount_amount >= 0 AND amount::BIGINT = total_price::BIGINT - discount_amount::BIGINT AND amount >= 100)
);

-- 한 예매에 살아 있는(READY·IN_PROGRESS·DONE) 결제는 하나다. 끝난 결제(FAILED·CANCELED)는 여러 개 남을 수 있다
CREATE UNIQUE INDEX uk_p_payments_live_reservation
    ON p_payments (reservation_id)
    WHERE status IN ('READY', 'IN_PROGRESS', 'DONE');

-- 복구 잡: 만료된 준비
CREATE INDEX ix_p_payments_ready_expires
    ON p_payments (expires_at)
    WHERE status = 'READY';

-- 복구 잡: 결과를 모르는 승인. 결제는 차단하지 않고 결과 확정 시한(1분)이 지나면 FAILED로 끝낸다
CREATE INDEX ix_p_payments_in_progress_next_attempt
    ON p_payments (next_attempt_at)
    WHERE status = 'IN_PROGRESS';

-- 최소 대사: PG 승인을 불렀는데 FAILED로 끝나 아직 확인하지 않은 결제
CREATE INDEX ix_p_payments_reconcile
    ON p_payments (next_reconcile_at, id)
    WHERE status = 'FAILED' AND approve_requested_at IS NOT NULL AND next_reconcile_at IS NOT NULL;

CREATE TABLE p_refunds
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          BIGINT       NOT NULL,
    reservation_id      BIGINT       NOT NULL,
    refund_amount       INT          NOT NULL,
    reason              VARCHAR(30)  NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    cancel_attempt      INT          NOT NULL DEFAULT 0,
    execution_version   BIGINT       NOT NULL DEFAULT 0 CONSTRAINT ck_p_refunds_execution_version CHECK (execution_version >= 0),
    recovery_mode       VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    verification_reason VARCHAR(80),
    restriction_started_at TIMESTAMP,
    slow_started_at     TIMESTAMP,
    slow_attempts       INT NOT NULL DEFAULT 0,
    cancel_key_created_at TIMESTAMP,
    pg_cancel_id        VARCHAR(200),
    failure_code        VARCHAR(80),
    failure_message     VARCHAR(255),
    requested_at        TIMESTAMP,
    refunded_at         TIMESTAMP,
    next_attempt_at     TIMESTAMP,
    recovery_started_at TIMESTAMP,
    recovery_attempts   INT          NOT NULL DEFAULT 0,
    recovery_blocked    BOOLEAN      NOT NULL DEFAULT FALSE,
    last_error          VARCHAR(80),
    created_at          TIMESTAMP    NOT NULL,
    created_by          VARCHAR(100) NOT NULL,
    updated_at          TIMESTAMP    NOT NULL,
    updated_by          VARCHAR(100) NOT NULL,
    deleted_at          TIMESTAMP,
    deleted_by          VARCHAR(100),

    CONSTRAINT fk_p_refunds_payment FOREIGN KEY (payment_id) REFERENCES p_payments (id),
    -- 결제 하나에 환불 행 하나. 사용자 환불과 자동 취소(AUTO_VOID)가 겹쳐도 같은 행을 쓴다
    CONSTRAINT uk_p_refunds_payment_id UNIQUE (payment_id),
    CONSTRAINT ck_p_refunds_status CHECK (status IN ('WAITING', 'REQUESTED', 'DONE', 'FAILED', 'SKIPPED')),
    CONSTRAINT ck_p_refunds_reason CHECK (reason IN ('USER_CANCEL', 'SCHEDULE_CANCELED', 'CONFIRM_FAILED', 'AUTO_VOID')),
    CONSTRAINT ck_p_refunds_amount CHECK (refund_amount > 0),
    CONSTRAINT ck_p_refunds_recovery_mode CHECK (recovery_mode IN ('ACTIVE','SLOW','VERIFY_ONLY','PAUSED')),
    CONSTRAINT ck_p_refunds_slow_attempts CHECK (slow_attempts >= 0),
    CONSTRAINT ck_p_refunds_blocked_mode CHECK (NOT recovery_blocked OR recovery_mode = 'PAUSED'),
    CONSTRAINT ck_p_refunds_failed_mode CHECK (status <> 'FAILED' OR recovery_mode IN ('VERIFY_ONLY','PAUSED'))
);

-- 복구 잡: 결과를 모르는 취소
CREATE INDEX ix_p_refunds_requested_next_attempt
    ON p_refunds (next_attempt_at)
    WHERE status IN ('REQUESTED','FAILED') AND recovery_mode <> 'PAUSED' AND recovery_blocked = FALSE;

-- 최종 운영 명령 결과. 자동 거래 전이 이력이나 PG 작업 큐가 아니다.
